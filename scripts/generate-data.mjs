import fs from "node:fs";
import path from "node:path";

/**
 * Generates src/data/season.ts from the verified research files in ./research.
 * Run with: node scripts/generate-data.mjs
 */
const root = process.cwd();
const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(root, "research", name), "utf8"));

const team = read("team-25145.json");
const events = read("events.json").events;
const matches = read("matches.json").matches;

const SEASONS = [
  { id: "2022-23", label: "2022–23", game: "CENTERSTAGE" },
  { id: "2023-24", label: "2023–24", game: "INTO THE DEEP" },
  { id: "2024-25", label: "2024–25", game: "DECODE" },
  { id: "2025-26", label: "2025–26", game: "BIOBUZZ" },
];

const seasonIdOf = (seasonField) => {
  const prefix = String(seasonField || "").slice(0, 7);
  const found = SEASONS.find((s) => prefix.startsWith(s.id));
  return found ? found.id : null;
};

const oprRows = team.op_ranking_stats || [];
const findOpr = (eventName) =>
  oprRows.find(
    (row) => row.event.includes(eventName) || eventName.includes(row.event),
  ) || null;

const normalizedMatches = matches.map((m) => ({
  season: seasonIdOf(m.season) ?? "unknown",
  event: m.event,
  match: m.match_number,
  date: m.date,
  alliance: String(m.alliance).toLowerCase(),
  result: m.result === "Tie" ? "T" : m.result,
  score: `${m.team_score}-${m.opponent_score}`,
  teamScore: m.team_score,
  opponentScore: m.opponent_score,
  opponent: (m.opponents || []).map((o) => `#${o.team}`).join(" & "),
}));

const seasons = SEASONS.map((seasonDef) => {
  const seasonEvents = events
    .filter((e) => seasonIdOf(e.season) === seasonDef.id)
    .map((e) => {
      const opr = findOpr(e.event_name);
      return {
        season: seasonDef.id,
        name: e.event_name,
        location: e.location,
        date: e.date,
        placement: e.placement ?? null,
        awards: e.awards || [],
        rankNote: e.rank_note || null,
        source: e.source,
        opr: opr ? opr.opr : null,
        npOpr: opr ? opr.npl_opr : null,
        qualRank: opr ? opr.qual_rank : null,
        qualRankTotal: opr ? opr.qual_rank_total : null,
        eventRecord: opr ? opr.event_record : null,
      };
    });

  const seasonMatches = normalizedMatches.filter(
    (m) => m.season === seasonDef.id,
  );
  const wins = seasonMatches.filter((m) => m.result === "W").length;
  const losses = seasonMatches.filter((m) => m.result === "L").length;
  const ties = seasonMatches.filter((m) => m.result === "T").length;

  return {
    id: seasonDef.id,
    label: seasonDef.label,
    game: seasonDef.game,
    matchesPlayed: seasonMatches.length,
    wins,
    losses,
    ties,
    opr: null,
    rank: seasonEvents.find((e) => e.placement)?.placement ?? null,
    awards: seasonEvents.flatMap((e) => e.awards),
    events: seasonEvents,
    matches: seasonMatches,
    pending: false,
  };
});

const teamProfile = {
  number: team.team_number,
  name: team.full_name,
  institution: team.institution,
  location: team.location,
  rookieYear: team.rookie_year,
  league: "Romania South",
  program: "Nație Prin Educație / FTC Romania",
  registrationId: team.registration_records[0]?.team_id ?? null,
  sponsor: team.sponsors[0]?.name ?? null,
};

const leagueStanding = {
  season: "2024-25",
  rank: team.league_standing_2025.rank,
  total: team.league_standing_2025.total,
  record: team.league_standing_2025.w_l_t,
  plays: team.league_standing_2025.plays,
  matchPoints: team.league_standing_2025.match_points,
  rs: team.league_standing_2025.rs,
  url: team.league_standing_2025.url,
};

const allMatches = seasons.flatMap((s) => s.matches);
const sources = team.sources || [];

const output = `// AUTO-GENERATED by scripts/generate-data.mjs — do not edit by hand.
// Source: research/{team-25145,events,matches}.json (verified 2026-11-17).

export type EventRecord = {
  season: string;
  name: string;
  location: string;
  date: string;
  placement: string | null;
  awards: string[];
  rankNote: string | null;
  source: string;
  opr: number | null;
  npOpr: number | null;
  qualRank: number | null;
  qualRankTotal: number | null;
  eventRecord: string | null;
};

export type MatchResult = {
  season: string;
  event: string;
  match: string;
  date: string;
  alliance: "red" | "blue";
  result: "W" | "L" | "T";
  score: string;
  teamScore: number | null;
  opponentScore: number | null;
  opponent: string;
};

export type SeasonSummary = {
  id: string;
  label: string;
  game: string;
  matchesPlayed: number;
  wins: number;
  losses: number;
  ties: number;
  opr: number | null;
  rank: string | null;
  awards: string[];
  events: EventRecord[];
  matches: MatchResult[];
  pending: boolean;
};

export const teamProfile = ${JSON.stringify(teamProfile, null, 2)};

export const leagueStanding = ${JSON.stringify(leagueStanding, null, 2)};

export const seasons: SeasonSummary[] = ${JSON.stringify(seasons, null, 2)};

export const season: SeasonSummary =
  seasons.find((s) => s.id === "2024-25") ?? seasons[0];

export const allMatches: MatchResult[] = ${JSON.stringify(allMatches, null, 2)};

export const dataSources: string[] = ${JSON.stringify(sources, null, 2)};
`;

const outPath = path.join(root, "src", "data", "season.ts");
fs.writeFileSync(outPath, output, "utf8");

for (const s of seasons) {
  console.log(
    `${s.label} ${s.game}: ${s.matchesPlayed}M ${s.wins}W-${s.losses}L-${s.ties}T · events ${s.events.length} · awards ${s.awards.length}`,
  );
}
console.log(`\nWrote ${outPath} (${output.length} bytes)`);
